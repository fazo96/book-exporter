// The PDF's Typst source: the book's settings as a `cfg` dictionary, the
// functions in assets/book.typ, the page and text setup, the project's
// custom.typ (after all of that, so it can override any of it), the cover and
// title pages, then the body pandoc wrote. Pure, so tests run it.

import { authorLine, type BookConfig, pageSize } from "../config.ts";
import { fontById } from "../fonts.ts";
import { sceneBreakGlyph } from "./metadata.ts";

/** A Typst string literal. */
export function typstStr(s: string): string {
  return `"${s.replace(/[\\"]/g, (c) => `\\${c}`).replace(/\n/g, "\\n")}"`;
}

const mm = (n: number) => `${Math.round(n * 100) / 100}mm`;
const font = (id: string) => typstStr(fontById(id)?.typst ?? "Libertinus Serif");

/** "en-US" → lang "en", region "us" (Typst's hyphenation and quotes go by them). */
export function langRegion(language: string): { lang: string; region: string | null } {
  const [lang, region] = language.toLowerCase().split(/[-_]/);
  return { lang: /^[a-z]{2,3}$/.test(lang) ? lang : "en", region: region && /^[a-z]{2}$/.test(region) ? region : null };
}

export function typstConfig(c: BookConfig, cover: string | null): string {
  const t = c.typography;
  const p = c.pdf;
  const { width, height } = pageSize(p);
  const glyph = sceneBreakGlyph(c.structure);
  const entries: [string, string][] = [
    ["title", typstStr(c.metadata.title)],
    ["subtitle", typstStr(c.metadata.subtitle)],
    ["authors", typstStr(authorLine(c))],
    ["publisher", typstStr(c.metadata.publisher)],
    ["body-font", font(t.bodyFont)],
    ["heading-font", font(t.headingFont)],
    ["mono-font", font(t.monoFont)],
    ["heading-case", typstStr(t.headingCase)],
    ["heading-weight", String(t.headingWeight)],
    ["heading-tracking", `${t.headingTracking}em`],
    ["heading-align", t.headingAlign],
    ["page-numbers", String(p.pageNumbers)],
    ["running-heads", typstStr(p.runningHeads)],
    ["open-recto", String(p.openRecto)],
    ["cover", cover && p.coverPage ? typstStr(cover) : "none"],
    ["toc", String(c.structure.toc)],
    ["toc-depth", String(c.structure.tocDepth)],
    ["scene-break", glyph ? typstStr(glyph) : "none"],
    ["end-mark", typstStr(c.structure.endMark)],
    ["end-text", typstStr(c.structure.endMarkText)],
    ["page-width", mm(width)],
    ["page-height", mm(height)],
  ];
  return `#let cfg = (\n${entries.map(([k, v]) => `  ${k}: ${v},`).join("\n")}\n)\n`;
}

export function typstSetup(c: BookConfig): string {
  const t = c.typography;
  const p = c.pdf;
  const m = p.margins;
  const { lang, region } = langRegion(c.metadata.language);
  // Typst's leading is the gap between lines, not the baseline distance: about
  // the line height less the face's cap height.
  const leading = Math.max(0.2, t.lineHeight - 0.7).toFixed(2);
  const spaced = t.paragraphStyle === "spaced";
  return `#set document(title: cfg.title, author: cfg.authors)

#set page(
  width: cfg.page-width,
  height: cfg.page-height,
  margin: (top: ${mm(m.top)}, bottom: ${mm(m.bottom)}, inside: ${mm(m.inside)}, outside: ${mm(m.outside)}),
  header: running-head(),
  footer: folio(),
)

#set text(font: cfg.body-font, size: ${t.fontSize}pt, lang: ${typstStr(lang)}${region ? `, region: ${typstStr(region)}` : ""}, hyphenate: ${t.hyphenate})
#set par(
  justify: ${t.justify},
  leading: ${leading}em,
  spacing: ${spaced ? "0.9em" : `${leading}em`},
  first-line-indent: ${spaced ? "0em" : `${t.indent}em`},
)

// Headings are placed and styled by the openers (part-page, chapter-opener…);
// any other heading is a plain display line.
// Typst sets headings bold and larger by default; the display type decides here.
#show heading: set text(weight: cfg.heading-weight, size: 1em)
#show heading: it => block(it.body)
#show heading.where(level: 4): it => block(above: 1.6em, below: 1em, display(size: 0.95em)[#it.body])
#show heading.where(level: 5): it => block(above: 1.4em, below: 0.8em, display(size: 0.9em)[#it.body])

#show raw: set text(font: cfg.mono-font, size: 0.85em)
#show raw.where(block: true): it => block(inset: (left: 1.5em), it)
#set quote(block: true)
#show quote.where(block: true): it => pad(left: 1.5em, right: 1.5em, it.body)
#show link: it => underline(offset: 1.6pt, stroke: 0.4pt, it)
`;
}

export function typstDocument(input: { config: BookConfig; library: string; custom: string; body: string; cover: string | null }): string {
  const { config: c } = input;
  return [
    "// Generated by book-exporter. Edit the book's settings or custom.typ, not this file.",
    typstConfig(c, input.cover),
    input.library,
    typstSetup(c),
    input.custom.trim() ? `// ---------------------------------------------------------- custom.typ\n${input.custom}\n` : "",
    "#cover-page()",
    c.pdf.titlePage ? "#title-page()" : "",
    "",
    input.body,
  ].join("\n");
}
